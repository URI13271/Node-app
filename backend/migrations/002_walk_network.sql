-- 002_walk_network.sql : 보행망 테이블 (보행 경로 적용, 백엔드 설계서 v2.4 2.5.2 추가분)
-- 지역(area_key) 단위로 OSM 보행망을 보관한다. 시드 적재(load_seed)가 지역마다 지우고 다시 넣는다.
-- 앱은 이 표를 읽지 않는다(사전 계산 경로 원칙). 적재 검사와 경로 생성 근거 보관용이다.
CREATE TABLE walk_network_feature (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    area_key  varchar(50) NOT NULL,
    kind      varchar(20) NOT NULL,
    geom      geometry(Geometry, 4326) NOT NULL,
    source    varchar(30) NOT NULL DEFAULT 'osm',
    loaded_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_walk_network_feature PRIMARY KEY (id),
    CONSTRAINT ck_walk_network_feature_kind CHECK (kind IN
        ('footway','sidewalk','crossing','steps','pedestrian','path','service','road','pedestrian_area','crossing_node')),
    CONSTRAINT ck_walk_network_feature_geom_type CHECK (
        (kind = 'crossing_node' AND GeometryType(geom) = 'POINT')
        OR (kind = 'pedestrian_area' AND GeometryType(geom) = 'POLYGON')
        OR (kind NOT IN ('crossing_node','pedestrian_area') AND GeometryType(geom) = 'LINESTRING')),
    CONSTRAINT ck_walk_network_feature_source CHECK (source IN ('osm','manual'))
);

CREATE INDEX ix_walk_network_feature_geom     ON walk_network_feature USING gist (geom);
CREATE INDEX ix_walk_network_feature_area_key ON walk_network_feature (area_key, kind);
