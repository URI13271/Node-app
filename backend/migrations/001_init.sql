-- 001_init.sql : MVP 스키마 7개 테이블 (백엔드 설계서 v2.2 2.5.2, 2.5.3 / 테이블 정의서 v1.0)
-- 명명 규칙: pk_, fk_, uq_, ix_, ck_ (설계서 2.1.5)
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE place (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    seed_key         varchar(50),
    name             varchar(100) NOT NULL,
    category         varchar(30)  NOT NULL,
    address          varchar(200),
    location         geometry(Point, 4326) NOT NULL,
    description      text,
    cover_image_url  text,
    camera_bearing   double precision,
    camera_pitch     double precision,
    camera_zoom      double precision,
    arrival_radius_m integer NOT NULL DEFAULT 150,
    last_verified_at timestamptz,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_place PRIMARY KEY (id),
    CONSTRAINT uq_place_seed_key UNIQUE (seed_key),
    CONSTRAINT ck_place_category CHECK (category IN ('pension','campsite','temple','restaurant','trailhead','attraction','campus','other')),
    CONSTRAINT ck_place_arrival_radius_m CHECK (arrival_radius_m BETWEEN 10 AND 1000),
    CONSTRAINT ck_place_camera_bearing CHECK (camera_bearing >= 0 AND camera_bearing < 360),
    CONSTRAINT ck_place_camera_pitch CHECK (camera_pitch BETWEEN 0 AND 85),
    CONSTRAINT ck_place_camera_zoom CHECK (camera_zoom BETWEEN 0 AND 22),
    CONSTRAINT ck_place_camera_all_or_none CHECK (num_nulls(camera_bearing, camera_pitch, camera_zoom) IN (0, 3))
);

CREATE TABLE building (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id    bigint NOT NULL,
    name        varchar(100),
    footprint   geometry(Polygon, 4326) NOT NULL,
    height_m    double precision,
    floor_count integer,
    description text,
    is_target   boolean NOT NULL DEFAULT false,
    source      varchar(30) NOT NULL,
    CONSTRAINT pk_building PRIMARY KEY (id),
    CONSTRAINT fk_building_place_id FOREIGN KEY (place_id) REFERENCES place (id) ON DELETE CASCADE,
    CONSTRAINT ck_building_footprint_valid CHECK (ST_IsValid(footprint)),
    CONSTRAINT ck_building_height_m CHECK (height_m > 0),
    CONSTRAINT ck_building_floor_count CHECK (floor_count > 0),
    CONSTRAINT ck_building_source CHECK (source IN ('osm','public_data','vworld','manual'))
);

CREATE TABLE entrance (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id         bigint NOT NULL,
    name             varchar(100) NOT NULL,
    location         geometry(Point, 4326) NOT NULL,
    description      text,
    is_main          boolean NOT NULL DEFAULT false,
    last_verified_at timestamptz,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_entrance PRIMARY KEY (id),
    CONSTRAINT fk_entrance_place_id FOREIGN KEY (place_id) REFERENCES place (id) ON DELETE CASCADE,
    CONSTRAINT uq_entrance_place_id_name UNIQUE (place_id, name)
);

CREATE TABLE parking_lot (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id         bigint NOT NULL,
    name             varchar(100) NOT NULL,
    location         geometry(Point, 4326) NOT NULL,
    capacity         integer,
    is_free          boolean,
    description      text,
    priority         smallint NOT NULL DEFAULT 1,
    area             geometry(Polygon, 4326),
    camera_bearing   double precision,
    camera_pitch     double precision,
    camera_zoom      double precision,
    last_verified_at timestamptz,
    CONSTRAINT pk_parking_lot PRIMARY KEY (id),
    CONSTRAINT fk_parking_lot_place_id FOREIGN KEY (place_id) REFERENCES place (id) ON DELETE CASCADE,
    CONSTRAINT uq_parking_lot_place_id_name UNIQUE (place_id, name),
    CONSTRAINT ck_parking_lot_capacity CHECK (capacity >= 0),
    CONSTRAINT ck_parking_lot_priority CHECK (priority >= 1),
    CONSTRAINT ck_parking_lot_camera_bearing CHECK (camera_bearing >= 0 AND camera_bearing < 360),
    CONSTRAINT ck_parking_lot_camera_pitch CHECK (camera_pitch BETWEEN 0 AND 85),
    CONSTRAINT ck_parking_lot_camera_zoom CHECK (camera_zoom BETWEEN 0 AND 22),
    CONSTRAINT ck_parking_lot_camera_all_or_none CHECK (num_nulls(camera_bearing, camera_pitch, camera_zoom) IN (0, 3))
);

CREATE TABLE landmark (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id    bigint NOT NULL,
    name        varchar(100) NOT NULL,
    location    geometry(Point, 4326) NOT NULL,
    description text,
    image_url   text,
    CONSTRAINT pk_landmark PRIMARY KEY (id),
    CONSTRAINT fk_landmark_place_id FOREIGN KEY (place_id) REFERENCES place (id) ON DELETE CASCADE
);

CREATE TABLE walk_route (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    parking_lot_id bigint NOT NULL,
    entrance_id    bigint NOT NULL,
    path           geometry(LineString, 4326) NOT NULL,
    distance_m     double precision,
    walk_time_min  integer,
    description    text,
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_walk_route PRIMARY KEY (id),
    CONSTRAINT fk_walk_route_parking_lot_id FOREIGN KEY (parking_lot_id) REFERENCES parking_lot (id) ON DELETE CASCADE,
    CONSTRAINT fk_walk_route_entrance_id FOREIGN KEY (entrance_id) REFERENCES entrance (id) ON DELETE CASCADE,
    CONSTRAINT uq_walk_route_parking_lot_id_entrance_id UNIQUE (parking_lot_id, entrance_id),
    CONSTRAINT ck_walk_route_path_npoints CHECK (ST_NPoints(path) >= 2),
    CONSTRAINT ck_walk_route_walk_time_min CHECK (walk_time_min > 0)
);

CREATE TABLE walk_route_step (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    walk_route_id  bigint NOT NULL,
    step_order     integer NOT NULL,
    landmark_id    bigint,
    instruction    text NOT NULL,
    location       geometry(Point, 4326) NOT NULL,
    camera_bearing double precision,
    camera_pitch   double precision,
    camera_zoom    double precision,
    updated_at     timestamptz DEFAULT now(),
    updated_by     varchar(50),
    CONSTRAINT pk_walk_route_step PRIMARY KEY (id),
    CONSTRAINT fk_walk_route_step_walk_route_id FOREIGN KEY (walk_route_id) REFERENCES walk_route (id) ON DELETE CASCADE,
    CONSTRAINT fk_walk_route_step_landmark_id FOREIGN KEY (landmark_id) REFERENCES landmark (id) ON DELETE SET NULL,
    CONSTRAINT uq_walk_route_step_walk_route_id_step_order UNIQUE (walk_route_id, step_order),
    CONSTRAINT ck_walk_route_step_step_order CHECK (step_order >= 1),
    CONSTRAINT ck_walk_route_step_instruction_length CHECK (char_length(instruction) BETWEEN 1 AND 200),
    CONSTRAINT ck_walk_route_step_camera_bearing CHECK (camera_bearing >= 0 AND camera_bearing < 360),
    CONSTRAINT ck_walk_route_step_camera_pitch CHECK (camera_pitch BETWEEN 0 AND 85),
    CONSTRAINT ck_walk_route_step_camera_zoom CHECK (camera_zoom BETWEEN 0 AND 22),
    CONSTRAINT ck_walk_route_step_camera_all_or_none CHECK (num_nulls(camera_bearing, camera_pitch, camera_zoom) IN (0, 3))
);

-- GIST 6개
CREATE INDEX ix_place_location        ON place       USING gist (location);
CREATE INDEX ix_building_footprint    ON building    USING gist (footprint);
CREATE INDEX ix_entrance_location     ON entrance    USING gist (location);
CREATE INDEX ix_parking_lot_location  ON parking_lot USING gist (location);
CREATE INDEX ix_landmark_location     ON landmark    USING gist (location);
CREATE INDEX ix_walk_route_path       ON walk_route  USING gist (path);
-- B-tree 5개 (같은 칼럼으로 시작하는 UNIQUE가 없는 외래키)
CREATE INDEX ix_building_place_id              ON building (place_id);
CREATE INDEX ix_landmark_place_id              ON landmark (place_id);
CREATE INDEX ix_parking_lot_place_id_priority  ON parking_lot (place_id, priority);
CREATE INDEX ix_walk_route_entrance_id         ON walk_route (entrance_id);
CREATE INDEX ix_walk_route_step_landmark_id    ON walk_route_step (landmark_id);
